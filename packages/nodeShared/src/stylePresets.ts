export function getStylePreset(name: unknown, snapshot?: unknown): StylePreset | undefined {
  if (isCustomStyle(snapshot) && snapshot.name === name) return snapshot;
  return stylePresets.find(item => item.name === name) ?? customStyles.value.find(item => item.name === name);
}

export function getStylePrompt(name: unknown, snapshot?: unknown): string {
  const preset = getStylePreset(name, snapshot);
  if (!preset) return "";
  return `视觉风格（${preset.label}）：${preset.prompt}。以用户指定的主体、场景、动作、配色、构图和相机参数为准。只采用与这些要求相容的风格特征。`;
}
